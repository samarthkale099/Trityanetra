import { useEffect, useRef, useState } from 'react'
import { useMutation } from '@tanstack/react-query'
import { CheckCircle2, LoaderCircle, Lock, Send } from 'lucide-react'
import { examApi, type SubmitInput } from '@/features/exam/examApi'
import { reportMonitorEvent, type MonitorContext } from '@/features/exam/monitorApi'
import { Button } from '@/shared/components/ui/button'
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogTitle,
} from '@/shared/components/ui/dialog'
import { toast } from '@/shared/components/ui/toast'
import { cn } from '@/shared/lib/cn'

/**
 * The submit control.
 *
 * Idempotency is enforced at two levels, because one of them alone is not
 * enough:
 * - A ref latch (`inFlight`) blocks the second click in the same tick. `disabled`
 *   is applied on the next render, and two clicks inside one tick both read
 *   `disabled === false`.
 * - The `idempotencyKey` is generated once per attempt by the caller and reused
 *   on every request, so even a retry that escapes the latch, a second tab, or a
 *   replayed request stores one submission. The server de-duplicates on it.
 *
 * Once submitted the bar locks: the exam is over, and re-enabling a submit
 * button invites an accidental second attempt.
 */

export type SubmitState = 'idle' | 'confirming' | 'submitting' | 'success' | 'error'

export interface SubmitBarProps {
  testId: string
  context: MonitorContext
  /** Current editor contents. */
  code: string
  /** Stable for the life of the attempt. Generated by the exam shell. */
  idempotencyKey: string
  /** Every question's code, read at the moment of submitting. */
  getAnswers?: () => Record<string, string>
  /** True once a submission exists. Locks the bar. */
  locked: boolean
  onSubmitted: (submissionId: string) => void
  /** Where to go after a successful submit. */
  onDone?: () => void
  className?: string
}

export function SubmitBar({
  testId,
  context,
  code,
  idempotencyKey,
  getAnswers,
  locked,
  onSubmitted,
  onDone,
  className,
}: SubmitBarProps) {
  const [confirmOpen, setConfirmOpen] = useState(false)
  const [state, setState] = useState<SubmitState>('idle')
  const [errorMessage, setErrorMessage] = useState<string | null>(null)
  const inFlight = useRef(false)

  const submit = useMutation({
    mutationFn: (input: SubmitInput) => examApi.submit(testId, input),
    onSuccess: (submission) => {
      setState('success')
      setConfirmOpen(false)
      onSubmitted(submission.id)
      // The event goes out after the submission so the two cannot race, and a
      // failed report is queued rather than blocking the success path.
      void reportMonitorEvent(context, 'EXAM_SUBMITTED', { status: submission.status })
      toast.success('Submitted', {
        description: 'Your work is recorded. You cannot change it now.',
      })
    },
    onError: (error: Error) => {
      setState('error')
      setErrorMessage(error.message)
      setConfirmOpen(false)
      toast.error('Submission failed', { description: error.message })
    },
  })

  const handleConfirm = async () => {
    // Synchronous latch: see the note above on why `disabled` is not enough.
    if (inFlight.current || locked) return
    inFlight.current = true
    setState('submitting')
    setErrorMessage(null)
    try {
      await submit.mutateAsync({ code, language: context.language, idempotencyKey, answers: getAnswers?.() })
    } catch {
      // Reported by `onError`.
    } finally {
      inFlight.current = false
    }
  }

  // A keydown anywhere submits without a mouse. Guarded by the same latch and by
  // `locked`, so it cannot race the button.
  useEffect(() => {
    if (locked) return
    const handler = (event: KeyboardEvent) => {
      if ((event.metaKey || event.ctrlKey) && event.key === 'Enter') {
        event.preventDefault()
        setConfirmOpen(true)
      }
    }
    window.addEventListener('keydown', handler)
    return () => window.removeEventListener('keydown', handler)
  }, [locked])

  const isSubmitting = state === 'submitting'
  const isLocked = locked || state === 'success'

  return (
    <div className={cn('flex flex-col gap-2', className)}>
      <div className="flex flex-wrap items-center gap-3">
        <Button onClick={() => setConfirmOpen(true)} disabled={isLocked || isSubmitting}>
          {isSubmitting ? (
            <LoaderCircle className="h-4 w-4 animate-spin" aria-hidden="true" />
          ) : isLocked ? (
            <Lock className="h-4 w-4" aria-hidden="true" />
          ) : (
            <Send className="h-4 w-4" aria-hidden="true" />
          )}
          {isSubmitting ? 'Submitting' : isLocked ? 'Submitted' : 'Submit exam'}
        </Button>

        {!isLocked ? (
          <p className="text-xs text-ink-faint">
            Shortcut <kbd className="rounded border border-line px-1 py-0.5 font-mono">Ctrl</kbd>+
            <kbd className="rounded border border-line px-1 py-0.5 font-mono">Enter</kbd>
          </p>
        ) : null}

        {isLocked && onDone ? (
          <Button variant="secondary" onClick={onDone}>
            <CheckCircle2 className="h-4 w-4" aria-hidden="true" />
            Back to the lobby
          </Button>
        ) : null}
      </div>

      {state === 'error' && errorMessage ? (
        <p role="alert" className="text-xs font-medium text-danger">
          {errorMessage} Try submitting again.
        </p>
      ) : null}

      <Dialog open={confirmOpen} onOpenChange={(open) => !isSubmitting && setConfirmOpen(open)}>
        <DialogContent>
          <DialogTitle>Submit your exam?</DialogTitle>
          <DialogDescription>
            This is the end of your attempt. You will not be able to return to the editor or change
            your code afterwards.
          </DialogDescription>
          <div className="mt-5 flex justify-end gap-2">
            <Button variant="secondary" onClick={() => setConfirmOpen(false)} disabled={isSubmitting}>
              Keep working
            </Button>
            <Button onClick={() => void handleConfirm()} disabled={isSubmitting}>
              {isSubmitting ? (
                <LoaderCircle className="h-4 w-4 animate-spin" aria-hidden="true" />
              ) : null}
              {isSubmitting ? 'Submitting' : 'Submit exam'}
            </Button>
          </div>
        </DialogContent>
      </Dialog>
    </div>
  )
}
